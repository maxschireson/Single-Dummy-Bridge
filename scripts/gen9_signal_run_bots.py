#!/usr/bin/env python3
"""Write configs/gen9-signal-run-bots.json: the Gen 8 prototype bots plus the Gen 9 signal bots, for box jobs.

scripts/gen9_match.py takes one --bots file; the signal runs (docs/gen9/signals-runs.md) need 8p-32 and 8x-32
from configs/gen8-proto-bots.json beside the bots of configs/gen9-signal-bots.json. Generated: edit the two
sources and run this again (tests/test_gen9_signals.py checks that the file matches them).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def merged():
    out = json.loads((ROOT / 'configs' / 'gen8-proto-bots.json').read_text())
    out.update({k: v for k, v in json.loads((ROOT / 'configs' / 'gen9-signal-bots.json').read_text()).items() if not k.startswith('_')})
    out['_note'] = 'Generated by scripts/gen9_signal_run_bots.py from configs/gen8-proto-bots.json and configs/gen9-signal-bots.json; do not edit.'
    return out


if __name__ == '__main__':
    (ROOT / 'configs' / 'gen9-signal-run-bots.json').write_text(json.dumps(merged(), indent=1) + '\n')
