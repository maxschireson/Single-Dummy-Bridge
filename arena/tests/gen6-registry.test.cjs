const assert=require('node:assert/strict');
const R=require('../reporting.js'),registry=require('../gen6-sources.json');
R.applyRegistry(registry);
const baseline=R.sources.find(s=>s.key==='gen6');
const future={key:'gen6codexbenfollowups',group:'gen6',generation:6,variant:'6',environment:'codex',name:'BEN followups',branch:'arena-gen6-codex-ben-followups-feed',cohort:'f'.repeat(64)};
const changed=structuredClone(registry);changed.sources.unshift(future);changed.sources.find(s=>s.key==='gen6').retired=true;changed.sources.find(s=>s.key==='gen6').revision='a'.repeat(40);
R.applyRegistry(changed);
assert.equal(R.latestScope,'gen6');assert.equal(R.latestSource.key,future.key);
assert.ok(R.pickSources('latest').some(s=>s.cohort===baseline.cohort));
const record=(id,pair)=>({id:String(id),index:id,pair,completed_epoch:1,family:'family-'+id,imps:2,own_imps:3,scores:[0,0],contracts:[]});
const input=(source,records)=>({source,data:{generated_epoch:10,target:records.length,failures:0,order:['6-32','6-256','ben','ben32'],own_views:{}},index:{records}});
const early=R.sources.find(s=>s.key==='gen6chatgptearly');
const old=input(early,[record(1,'6-32~ben')]),allowed=input(future,[record(2,'6-32~ben'),record(3,'6-256~ben32')]);
const rows=R.rowsFor([old,allowed],'latest').rows;
assert.equal(rows.length,2);assert.deepEqual(rows.map(r=>r.pair),['6-32~ben','6-256~ben32']);
assert.equal(R.view(rows).groups['6-256~ben32'].n,1);assert.equal(R.labels.ben32,'BEN (32)');
assert.equal(old.index.records.length,1,'Archived raw records are preserved');
const historical={...early,key:'former-selection-key'};
assert.equal(R.rowsFor([input(historical,[record(4,'6-32~3')])],'gen6chatgpt','common',{[historical.cohort]:10}).rows.length,1,'Pinned historical cohorts survive source-key rollover');
assert.throws(()=>R.applyRegistry({...registry,sources:[...registry.sources,registry.sources[0]]}),/repeated/);
console.log('PASS live registry preserves the Gen6 scope, keeps old snapshots, separates BEN budgets and counts newly authorized fast/BEN games');
